"""
Abstract Base Class for Large Language Model (LLM) Providers.
Defines standard interfaces for non-streaming, streaming, and tool-augmented generation.
"""

from abc import ABC, abstractmethod
from typing import Any, AsyncIterator, Dict, List, Optional
from app.ai.schemas import ChatMessage, LLMResponse


class LLMProvider(ABC):
    """Abstract Base Class for LLM providers."""

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Unique provider identifier (e.g. 'gemini', 'openai')."""
        pass

    @property
    @abstractmethod
    def default_model(self) -> str:
        """Default model name for this provider."""
        pass

    @abstractmethod
    async def generate(
        self,
        messages: List[ChatMessage],
        system_instruction: Optional[str] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_output_tokens: Optional[int] = None,
        timeout: Optional[float] = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """
        Generates a complete response for a sequence of chat messages.

        :param messages: Chronological list of chat turns (user/assistant).
        :param system_instruction: Guiding prompt / persona for the model.
        :param model: Specific model identifier override.
        :param temperature: Sampling temperature.
        :param max_output_tokens: Maximum tokens in the generated response.
        :param timeout: Request timeout in seconds.
        :return: LLMResponse containing the generated text and metadata.
        """
        pass

    @abstractmethod
    async def stream(
        self,
        messages: List[ChatMessage],
        system_instruction: Optional[str] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_output_tokens: Optional[int] = None,
        timeout: Optional[float] = None,
        **kwargs: Any,
    ) -> AsyncIterator[str]:
        """
        Streams response tokens/chunks as they are generated by the model.

        :param messages: Chronological list of chat turns.
        :param system_instruction: Guiding prompt / persona for the model.
        :param model: Specific model identifier override.
        :param temperature: Sampling temperature.
        :param max_output_tokens: Maximum tokens in the generated response.
        :param timeout: Request timeout in seconds.
        :return: AsyncIterator yielding string chunks.
        """
        pass

    @abstractmethod
    async def generate_with_tools(
        self,
        messages: List[ChatMessage],
        tools: List[Any],
        system_instruction: Optional[str] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_output_tokens: Optional[int] = None,
        timeout: Optional[float] = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """
        Generates a response given a set of callable tool / function definitions.

        :param messages: Chronological list of chat turns.
        :param tools: List of tool specifications/functions.
        :param system_instruction: Guiding prompt / persona for the model.
        :return: LLMResponse containing text or requested tool calls.
        """
        pass

    async def stream_tool_response(
        self,
        messages: List[ChatMessage],
        raw_model_content: Any,
        tool_results: List[Dict[str, Any]],
        tools: Optional[List[Any]] = None,
        system_instruction: Optional[str] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_output_tokens: Optional[int] = None,
        timeout: Optional[float] = None,
        **kwargs: Any,
    ) -> AsyncIterator[str]:
        """
        Streams the final response after supplying tool results back to the model.
        """
        raise NotImplementedError("stream_tool_response not implemented for this provider")
